        """Values land in the exact template cells (cover D-column, confirmation C-column)."""
        from django.utils import timezone
        from inspections.services.report_generator import TEMPLATE_PATH
        if not os.path.exists(TEMPLATE_PATH):
            self.skipTest('report_template.xlsx not bundled')

        inspection = self.make_inspection()
        inspection.brand_name = 'Gucci'
        inspection.error_setting_fixed_count = 3
        inspection.device_counts = {'显示器数量': 6}
        inspection.save()
