class ReportGoldenParityTests(TestCase):
    """Authoritative parity: reconstruct devices from a REAL EUS-generated report and
    assert our ported transforms reproduce its cover_page counts and categories.

    Skips when no golden report is available locally (e.g. CI). Set
    INSPECTION_GOLDEN_REPORT to point at a specific '... Report Per Store.xlsx'.
    """

    # Cover labels fed by devices that the EUS pipeline filters OUT of asset_list
    # (network gear + cash drawers), so they cannot be reconstructed from it.
    NON_ASSET_LIST_LABELS = {'Patch Panel', 'Router', 'Switch', 'AP', 'Cashdrawer'}

    def _find_golden(self):
        import glob
        override = os.environ.get('INSPECTION_GOLDEN_REPORT')
        if override and os.path.exists(override):
            return override
        pattern = (r'c:\Users\sean_\Documents\EUS_Device_Inspec\DeviceInspecFeishuAutomation'
                   r'\*\* Report Per Store.xlsx')
        matches = sorted(glob.glob(pattern))
        return matches[0] if matches else None

    def _read_golden(self, path):
        wb = load_workbook(path, data_only=True)
        al = wb['asset_list']
        header = {}
        for col in range(1, al.max_column + 1):
            value = al.cell(row=1, column=col).value
            if value:
                header[str(value).strip()] = col
        rows = []
        for r in range(2, al.max_row + 1):
            get = lambda name: al.cell(row=r, column=header[name]).value if name in header else None
            if all(get(n) in (None, '') for n in ('Category', 'SN', 'Asset ID')):
                continue
            rows.append({
                'category': get('Category'), 'brand_model': get('Brand-Model'),
                'sn': get('SN'), 'usage': get('Usage'), 'status': get('Status'),
            })
        cp = wb['cover_page']
        counts = {}
        for r in range(1, cp.max_row + 1):
            label = cp.cell(row=r, column=2).value
            if label is None:
                continue
            label = ' '.join(str(label).split())
            if label in COVER_PAGE_DEVICE_LABELS:
                value = cp.cell(row=r, column=4).value
                counts[label] = value if isinstance(value, int) else 0
        return rows, counts

    def test_cover_counts_match_golden(self):
        from types import SimpleNamespace
        from django.utils import timezone
        from inspections.constants import normalize_device_category

        golden = self._find_golden()
        if not golden:
            self.skipTest('No local EUS golden report available')
        rows, golden_counts = self._read_golden(golden)
        self.assertTrue(rows, 'golden asset_list had no rows')

        now = timezone.now()
        devices = []
        for row in rows:
            in_store = str(row['status'] or '').strip().lower() == 'in store'
            devices.append(SimpleNamespace(
                category=normalize_device_category(row['category']),
                usage=row['usage'] or '', brand_model=row['brand_model'] or '',
                status='in_store' if in_store else 'not_in_store',
                collected_at=now if in_store else None, is_new_device=False,
            ))

        computed = transforms.build_cover_page_summary_counts(devices)
        mismatches = {}
        for label in COVER_PAGE_DEVICE_LABELS:
            if label in self.NON_ASSET_LIST_LABELS:
                continue
            expected = golden_counts.get(label, 0)
            if computed.get(label, 0) != expected:
                mismatches[label] = {'golden': expected, 'computed': computed.get(label, 0)}
        self.assertEqual(mismatches, {}, f'cover_page count parity mismatch vs {os.path.basename(golden)}')
        # Sanity: the golden actually exercised the classifier (non-trivial data).
        self.assertGreater(sum(golden_counts.values()), 0)

    def test_category_normalization_is_idempotent_on_golden(self):
        from inspections.constants import normalize_device_category

        golden = self._find_golden()
        if not golden:
            self.skipTest('No local EUS golden report available')
        rows, _ = self._read_golden(golden)
        for row in rows:
            category = row['category']
            if category:
                # Golden categories are already canonical; normalizing must be a no-op.
                self.assertEqual(normalize_device_category(category), str(category).strip())
